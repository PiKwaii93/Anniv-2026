  legacy_entry.level,
  legacy_entry.title,
  '',
  legacy_entry.sort_order,
  false
from legacy_entries as legacy_entry
where not exists (
  select 1
  from public.iceberg_entries as current_entry
  where lower(trim(current_entry.title)) = lower(trim(legacy_entry.title))
);
